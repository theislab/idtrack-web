// The frontend's types of the api, generated from the api's OpenAPI document (../api/openapi.json), the only thing the
// api and the frontend share. `npm run types` writes src/api/schema.ts; `npm run types:check` fails when the file
// is not what the document gives (CI runs it, so a changed api cannot go unnoticed by the frontend).
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { format, resolveConfig } from "prettier";

const documentUrl = new URL("../../api/openapi.json", import.meta.url);
const target = fileURLToPath(new URL("../src/api/schema.ts", import.meta.url));
const header =
  "// Generated by scripts/generate-types.mjs from api/openapi.json: do not edit; run `npm run types`.\n\n";

const ast = await openapiTS(JSON.parse(await readFile(documentUrl, "utf8")), { exportType: true });
const text = await format(header + astToString(ast), { ...(await resolveConfig(target)), filepath: target });

if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== text) {
    console.error("src/api/schema.ts is not what api/openapi.json gives: run `npm run types` and commit the result.");
    process.exit(1);
  }
  console.log("src/api/schema.ts matches api/openapi.json");
} else {
  await writeFile(target, text);
  console.log("wrote src/api/schema.ts from api/openapi.json");
}
