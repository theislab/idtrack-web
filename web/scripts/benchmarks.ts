/** A pattern of strata as a family's document writes it (`d1_<id\|symbol>_<same\|cross>_<one\|dominant\|open>`,
 *  `b1_atR_<c>`, `c5_ccds_*`), as a regular expression over a stratum's code. */
export function strataPattern(pattern: string): RegExp {
  const source = pattern
    .replace(/\\\|/g, "|")
    .split(/(<[^>]*>|\*)/)
    .map((part) => {
      if (part === "*") return ".+";
      if (part === "<...>") return ".+";
      const options = /^<([^>]*)>$/.exec(part)?.[1];
      if (options !== undefined) return options.includes("|") ? `(?:${options.split("|").join("|")})` : ".+?";
      return part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    })
    .join("");
  return new RegExp(`^${source}$`);
}

/** The first clause of a reader's text, without its asides in brackets: up to its first semicolon (the rest of a
 *  cell holds counts and details), and where that is long, up to the comma that keeps it within a line or two. */
export function firstClause(text: string, room = 70): string {
  let flat = text;
  for (let previous = ""; previous !== flat;) {
    previous = flat;
    flat = flat.replace(/ ?\([^()]*\)/g, "");
  }
  let clause = (flat.split(/;\s/)[0] ?? "").replace(/\s+([,;:.])/g, "$1").trim();
  // What stands before a colon names the thing; what follows details it.
  const colon = clause.indexOf(": ");
  if (colon >= 12) clause = clause.slice(0, colon);
  if (clause.length <= room) return clause.replace(/[,:]$/, "");
  const cut = clause.lastIndexOf(", ", room);
  return (cut > 30 ? clause.slice(0, cut) : clause).replace(/[,:]$/, "");
}

/** What each stratum of a family asks, in its document's words (its section "The sets"): the row of the sets table
 *  whose strata name it (as written, or as a pattern with `<a|b>` parts), by what that row asks and the gloss the
 *  document writes in brackets after the stratum or its parts (`` `same`: the source release lies on the target's
 *  assembly ``); a stratum the table names only by its set (`e2_internal_name` of the set `e2`) by its set's row.
 *  A stratum the document does not describe has none: the page names it by its code. */
export function strataMeaningsOf(markdown: string, codes: readonly string[]): Record<string, string | null> {
  const lines = section(markdown, "## The sets");
  const start = lines.findIndex((l) => l.startsWith("|"));
  const out: Record<string, string | null> = {};
  if (start < 0) {
    for (const code of codes) out[code] = null;
    return out;
  }
  const end = lines.findIndex((l, i) => i > start && !l.startsWith("|"));
  const [header = [], ...rows] = tableRows(lines.slice(start, end < 0 ? lines.length : end));
  const column = (test: RegExp) => header.findIndex((h) => test.test(h));
  const strataAt = column(/^strat/);
  const whatAt = column(/^what/);
  const labelAt = strataAt === 0 ? -1 : 0;
  const glossesIn = (cell: string): Map<string, string> => {
    // `word`: gloss (up to the next `;` or `)`), and `word` gloss inside a bracket that defines a part (`<c>`: ...).
    const out = new Map<string, string>();
    for (const [, word = "", gloss = ""] of cell.matchAll(/`(\w+)`:\s*([^;`)]+)/g)) out.set(word, gloss.trim());
    for (const [, body = ""] of cell.matchAll(/\(`<\w+>`:\s*([^()]*(?:\([^()]*\)[^()]*)*)\)/g))
      for (const [, word = "", gloss = ""] of body.matchAll(/`(\w+)`\s+([^,`]+)/g))
        out.set(word, readerText(gloss).replace(/[,;]$/, "").trim());
    return out;
  };
  const described = rows.map((cells) => {
    const strata = strataAt >= 0 ? (cells[strataAt] ?? "") : "";
    const what = whatAt >= 0 ? firstClause(readerText(cells[whatAt] ?? "")) : "";
    const label = labelAt >= 0 ? (cells[labelAt] ?? "") : "";
    const patterns = [...strata.matchAll(/`([^`]+)`(?:\s*\(([^()]*(?:\([^()]*\)[^()]*)*)\))?/g)].map(
      ([, pattern = "", gloss]) => ({
        test: strataPattern(pattern),
        gloss: gloss && !gloss.includes("`") ? firstClause(readerText(gloss)) : null,
      }),
    );
    // A row named by its stratum alone (`A1`) or by its set (`` `e2` ``).
    const own = (strataAt === 0 ? strata : label).replace(/`/g, "").split(/,\s*/);
    return { patterns, own, what, label: plainCell(label).replace(/`/g, ""), glosses: glossesIn(strata) };
  });
  // The words of a code the document glosses elsewhere: in its truth (`one` (one gene, ...)), or in the sentence that
  // says what the strata are ("The strata are the direction of travel: `same`, `forward`, ...; each with `_handoff`
  // when ...").
  const elsewhere = new Map<string, string>();
  const truth = (() => {
    try {
      return section(markdown, "## Truth").join(" ");
    } catch {
      return "";
    }
  })();
  for (const [, word = "", gloss = ""] of truth.matchAll(/`(\w+)` \(([^()`]*(?:\([^()`]*\)[^()`]*)*)\)/g))
    elsewhere.set(word, firstClause(readerText(gloss), 80));
  const kinds = /The strata are ([^:]+): ([^.]*)\./.exec(lines.join(" "));
  const listed = new Map<string, string>();
  if (kinds) {
    const [, what = "", list = ""] = kinds;
    for (const [, word = ""] of list.matchAll(/`(\w+)`/g)) listed.set(word, readerText(what));
    for (const [, suffix = "", gloss = ""] of list.matchAll(/with `_(\w+)` ([^;`]+)/g))
      elsewhere.set(suffix, gloss.trim());
  }
  for (const code of codes) {
    const words = code.split(/[_:]/);
    const glossed = words.map((w) => elsewhere.get(w)).filter((g): g is string => Boolean(g));
    const parts = (row: (typeof described)[number]) =>
      words.map((w) => row.glosses.get(w)).filter((g): g is string => Boolean(g));
    const join = (...texts: (string | null | undefined)[]) =>
      [...new Set(texts.filter((t): t is string => Boolean(t)))].join("; ") || null;
    // A stratum measured in parts (`b2_moved_from: history continues`) is its stratum's, with the part in its words.
    const [base = code, part] = code.split(/:\s+/);
    if (part !== undefined && base !== code) {
      const whole = strataMeaningsOf(markdown, [base])[base];
      out[code] = whole ? `${whole}; ${part}` : null;
      continue;
    }
    const byPattern = described.find((row) => row.patterns.some((p) => p.test.test(code)));
    if (byPattern) {
      const p = byPattern.patterns.find((x) => x.test.test(code));
      const label = /^[a-z]\d+ (.+)$/.exec(byPattern.label)?.[1] ?? null;
      out[code] = join(label, byPattern.what, p?.gloss, ...parts(byPattern), ...glossed);
      continue;
    }
    const first = words[0] ?? "";
    if (listed.has(first)) {
      out[code] = join(`${listed.get(first) ?? ""}: ${first}`, ...glossed);
      continue;
    }
    const byOwn = described
      .filter((row) => row.own.some((name) => name && (code === name || code.startsWith(`${name}_`))))
      .sort((a, b) => Math.max(...b.own.map((n) => n.length)) - Math.max(...a.own.map((n) => n.length)))[0];
    out[code] = byOwn ? join(byOwn.what, ...glossed) : null;
  }
  return out;
}

/** The lines of a section: from its heading to the next heading of its level or above. */
export function section(markdown: string, heading: string): string[] {
  const lines = markdown.split("\n");
  const start = lines.findIndex((l) => l.trim() === heading);
  if (start < 0) throw new Error(`no section '${heading}'`);
  const level = /^#+/.exec(heading)?.[0].length ?? 0;
  const end = lines.findIndex((l, i) => i > start && /^#+\s/.test(l) && (/^#+/.exec(l)?.[0].length ?? 9) <= level);
  return lines.slice(start + 1, end < 0 ? lines.length : end);
}

const integer = (text: string): number => {
  if (!/^\d{1,3}(,\d{3})*$/.test(text)) throw new Error(`not a count: '${text}'`);
  return Number(text.replaceAll(",", ""));
};

/** The first table of a family's "On main" section that opens with `| family | organism |`: its totals. */
