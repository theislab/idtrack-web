// The frontend's types of the api, generated from the api's OpenAPI document (../api/openapi.json), the only thing the
// api and the frontend share. `npm run types` writes src/api/schema.ts (the types), src/api/shapes.ts (the shape of
// every answer, which the client checks each answer against before a page reads it) and src/api/timing.ts (what each
// metric of `Server-Timing` measures); `npm run types:check` fails when a file is not what the document gives (CI runs
// it, so a changed api cannot go unnoticed by the frontend).
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString, type OpenAPI3 } from "openapi-typescript";
import { format, resolveConfig } from "prettier";
import type { Shape } from "../src/api/shapeForm.ts";

/** What this generator reads of a JSON schema of the document (OpenAPI 3.1). */
interface Schema {
  $ref?: string;
  anyOf?: Schema[];
  oneOf?: Schema[];
  allOf?: Schema[];
  const?: unknown;
  type?: string | string[];
  prefixItems?: Schema[];
  items?: Schema;
  properties?: Record<string, Schema>;
  additionalProperties?: Schema | boolean;
  required?: string[];
}

interface Operation {
  responses?: Record<string, { content?: Record<string, { schema?: Schema }> }>;
}

interface Document {
  components?: {
    schemas?: Record<string, Schema>;
    headers?: Record<string, { "x-metrics"?: Record<string, string> }>;
  };
  paths?: Record<string, Record<string, Operation>>;
}

const documentUrl = new URL("../../api/openapi.json", import.meta.url);
const typesTarget = fileURLToPath(new URL("../src/api/schema.ts", import.meta.url));
const shapesTarget = fileURLToPath(new URL("../src/api/shapes.ts", import.meta.url));
const timingTarget = fileURLToPath(new URL("../src/api/timing.ts", import.meta.url));
const header = "// Generated by scripts/generate-types.ts from api/openapi.json: do not edit; run `npm run types`.\n\n";

const parsed: unknown = JSON.parse(await readFile(documentUrl, "utf8"));
/** The parts of the document the shapes are made from; openapi-typescript reads the whole of it. */
const document = parsed as Document;

/** The shape of one JSON schema of the document, in the compact form src/api/shape.ts reads: a type name, or an object
 *  `{a}` (a list), `{t}` (a list of fixed length), `{o, opt}` (an object with its required and optional fields; other
 *  fields are allowed), `{m}` (an object whose every value has one shape), `{u}` (one of several), `{r}` (a named
 *  schema). Enumerations and bounds are not part of a shape: a value the document does not list yet is not a fault of
 *  the answer's form, and the pages show any code as itself. */
function shapeOf(schema: Schema | boolean | undefined): Shape {
  if (typeof schema !== "object" || Object.keys(schema).length === 0) return "any";
  if (schema.$ref) return { r: schema.$ref.split("/").pop() ?? schema.$ref };
  const union = schema.anyOf ?? schema.oneOf;
  if (union) return { u: union.map(shapeOf) };
  if (schema.allOf) return schema.allOf.length === 1 ? shapeOf(schema.allOf[0]) : "any";
  if ("const" in schema && schema.type === undefined) return constShape(schema.const);
  if (Array.isArray(schema.type)) return { u: schema.type.map((type) => shapeOf({ ...schema, type })) };
  switch (schema.type) {
    case "string":
    case "integer":
    case "number":
    case "boolean":
    case "null":
      return schema.type;
    case "array":
      if (schema.prefixItems) return { t: schema.prefixItems.map(shapeOf) };
      return { a: shapeOf(schema.items) };
    case "object": {
      if (!schema.properties) {
        return schema.additionalProperties && schema.additionalProperties !== true
          ? { m: shapeOf(schema.additionalProperties) }
          : "object";
      }
      const required = new Set(schema.required ?? []);
      const o: Record<string, Shape> = {};
      const opt: Record<string, Shape> = {};
      for (const [name, property] of Object.entries(schema.properties)) {
        (required.has(name) ? o : opt)[name] = shapeOf(property);
      }
      return Object.keys(opt).length ? { o, opt } : { o };
    }
    default:
      return "any";
  }
}

/** The shape of a schema that is one constant value of JSON: the value's own type. */
function constShape(value: unknown): Shape {
  if (value === null) return "null";
  const kind = typeof value;
  return kind === "string" || kind === "number" || kind === "boolean" || kind === "object" ? kind : "any";
}

const schemas = Object.fromEntries(
  Object.entries(document.components?.schemas ?? {}).map(([name, schema]) => [name, shapeOf(schema)]),
);
/** The shape of each endpoint's JSON answer (status 200), by method and path below the api's base. */
const responses: Record<string, Shape> = {};
for (const [path, operations] of Object.entries(document.paths ?? {})) {
  for (const [method, operation] of Object.entries(operations)) {
    const schema = operation.responses?.["200"]?.content?.["application/json"]?.schema;
    if (!schema) continue;
    // Paths below the api's base, as the client names them (the document writes them from the site's root).
    const relative = path.replace(/^\/api\/v1(?=\/|$)/, "") || "/";
    responses[`${method.toUpperCase()} ${relative}`] = shapeOf(schema);
  }
}

const shapesText = await format(
  header +
    "// The shape of every answer the api's document describes (src/api/shape.ts reads and checks it).\n" +
    'import type { Shape } from "./shapeForm";\n\n' +
    `export const SCHEMAS: Record<string, Shape> = ${JSON.stringify(schemas)};\n\n` +
    `export const RESPONSES: Record<string, Shape> = ${JSON.stringify(responses)};\n`,
  { ...(await resolveConfig(shapesTarget)), filepath: shapesTarget },
);

// What each metric of `Server-Timing` measures: the api's one text of them (`x-metrics` of the header), so the page
// never says otherwise than the api.
const metrics = document.components?.headers?.["Server-Timing"]?.["x-metrics"];
if (!metrics) throw new Error("api/openapi.json gives no x-metrics of the Server-Timing header");
const timingText = await format(
  header +
    "// What each metric of the api's `Server-Timing` header measures, in the api's words (lib/serverTiming.ts reads\n" +
    "// the header).\n" +
    `export const TIMING_METRICS: Record<string, string> = ${JSON.stringify(metrics)};\n`,
  { ...(await resolveConfig(timingTarget)), filepath: timingTarget },
);

const ast = await openapiTS(parsed as OpenAPI3, { exportType: true });
const typesText = await format(header + astToString(ast), {
  ...(await resolveConfig(typesTarget)),
  filepath: typesTarget,
});

const outputs: [string, string, string][] = [
  [typesTarget, typesText, "src/api/schema.ts"],
  [shapesTarget, shapesText, "src/api/shapes.ts"],
  [timingTarget, timingText, "src/api/timing.ts"],
];
if (process.argv.includes("--check")) {
  let stale = false;
  for (const [target, text, name] of outputs) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== text) {
      console.error(`${name} is not what api/openapi.json gives: run \`npm run types\` and commit the result.`);
      stale = true;
    } else console.log(`${name} matches api/openapi.json`);
  }
  if (stale) process.exit(1);
} else {
  for (const [target, text, name] of outputs) {
    await writeFile(target, text);
    console.log(`wrote ${name} from api/openapi.json`);
  }
}
