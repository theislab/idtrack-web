// The known limitations of idtrack shown on the About page, generated from idtrack's own documentation: the section
// "Current Limitations" of docs/usage.rst at the idtrack commit the api is pinned to (api/uv.lock). Each item is the
// lead sentence idtrack writes in bold, as written; the page links to the whole section at that commit.
//
//   npm run limitations                      fetch docs/usage.rst of the pinned commit from GitHub, write the file
//   npm run limitations -- --from <file>     read a local copy of that docs/usage.rst instead (a checkout of the commit)
//   npm run limitations:check [-- --from <file>]   fail when src/generated/limitations.json is not what the page gives
//
// Run it after every change of the idtrack commit (SETUP.md, "The idtrack commit"); a unit test fails while the file
// names another commit than api/uv.lock.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname } from "node:path";
import { format, resolveConfig } from "prettier";

const lockUrl = new URL("../../api/uv.lock", import.meta.url);
const target = fileURLToPath(new URL("../src/generated/limitations.json", import.meta.url));
const REPOSITORY = "https://github.com/theislab/idtrack";

/** The idtrack commit of api/uv.lock (its git source, `...#<commit>`). */
export function pinnedCommit(lock) {
  const found = /source = \{ git = "https:\/\/github\.com\/theislab\/idtrack\.git\?[^"#]*#([0-9a-f]{40})" \}/.exec(
    lock,
  );
  if (!found) throw new Error("api/uv.lock names no git commit of idtrack");
  return found[1];
}

/** RST inline markup as the page writes text: ``code`` and `code` as `code`, roles by their target's last name. */
function plain(text) {
  return text
    .replace(/:py:\w+:`~?([^`]+)`/g, (_, name) => `\`${name.split(".").pop()}\``)
    .replace(/:ref:`([^`<]+?)\s*(<[^>]+>)?`/g, (_, label) => label.trim())
    .replace(/``([^`]+)``/g, "`$1`")
    .replace(/\s+/g, " ")
    .trim();
}

/** The section's introduction and its items' bold lead sentences. */
export function limitationsOf(rst) {
  const lines = rst.split("\n");
  const start = lines.findIndex((line, i) => line.trim() === "Current Limitations" && /^-+$/.test(lines[i + 1] ?? ""));
  if (start < 0) throw new Error("docs/usage.rst has no section 'Current Limitations'");
  const rest = lines.slice(start + 2);
  // The section ends where the next heading begins (a line of text underlined), or a label before it.
  const next = rest.findIndex(
    (line, i) => (/^\S/.test(line) && /^[-=~^]{3,}$/.test(rest[i + 1] ?? "")) || /^\.\. _[^:]+:$/.test(line),
  );
  const section = (next < 0 ? rest : rest.slice(0, next)).join("\n");
  const [intro, ...items] = section.split(/\n\* /);
  return {
    intro: plain(intro ?? ""),
    items: items.map((item) => {
      const lead = /^\*\*([\s\S]+?)\*\*/.exec(item.trimStart());
      if (!lead) throw new Error(`an item of the section has no bold lead: ${item.slice(0, 80)}`);
      // A lead that is the start of its sentence is marked as continued in idtrack's text.
      const text = plain(lead[1]);
      return /[.?!]$/.test(text) ? text : `${text} …`;
    }),
  };
}

const argument = (name) => {
  const at = process.argv.indexOf(name);
  return at < 0 ? null : process.argv[at + 1];
};

async function main() {
  const commit = pinnedCommit(await readFile(lockUrl, "utf8"));
  const from = argument("--from");
  const raw = `https://raw.githubusercontent.com/theislab/idtrack/${commit}/docs/usage.rst`;
  let rst;
  if (from) {
    rst = await readFile(from, "utf8");
  } else {
    const response = await fetch(raw);
    if (!response.ok) throw new Error(`${raw}: ${response.status}`);
    rst = await response.text();
  }
  const { intro, items } = limitationsOf(rst);
  const document = {
    about: "Generated by scripts/limitations.mjs from idtrack's docs/usage.rst at the commit: do not edit.",
    commit,
    source: `${REPOSITORY}/blob/${commit}/docs/usage.rst#current-limitations`,
    intro,
    items,
  };
  const text = await format(JSON.stringify(document), { ...(await resolveConfig(target)), filepath: target });
  if (process.argv.includes("--check")) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== text) {
      console.error(
        "src/generated/limitations.json is not what idtrack's Current Limitations give: run `npm run limitations`.",
      );
      process.exit(1);
    }
    console.log(`src/generated/limitations.json matches idtrack ${commit.slice(0, 12)} (${items.length} items)`);
  } else {
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, text);
    console.log(`wrote src/generated/limitations.json from idtrack ${commit.slice(0, 12)} (${items.length} items)`);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
