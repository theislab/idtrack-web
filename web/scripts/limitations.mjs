// The known limitations of idtrack shown on the About page, generated from idtrack's own documentation: the section
// "Limitations" of docs/limitations.rst at the idtrack commit the api is pinned to (api/uv.lock). Each of the section's
// subsections is one limitation, which idtrack opens with a lead sentence in bold; each item is that lead sentence, as
// written, and the page links to the section at that commit.
//
//   npm run limitations                   fetch docs/limitations.rst of the pinned commit from GitHub, write the file
//   npm run limitations -- --from <file>  read a local copy of that file instead (a checkout of the commit)
//   npm run limitations:check [-- --from <file>]   fail when src/generated/limitations.json is not what the page gives
//
// Run it after every change of the idtrack commit (SETUP.md, "The idtrack commit"); a unit test fails while the file
// names another commit than api/uv.lock.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname } from "node:path";
import { format, resolveConfig } from "prettier";

const lockUrl = new URL("../../api/uv.lock", import.meta.url);
const target = fileURLToPath(new URL("../src/generated/limitations.json", import.meta.url));
const REPOSITORY = "https://github.com/theislab/idtrack";

/** The idtrack commit of api/uv.lock (its git source, `...#<commit>`). */
export function pinnedCommit(lock) {
  const found = /source = \{ git = "https:\/\/github\.com\/theislab\/idtrack\.git\?[^"#]*#([0-9a-f]{40})" \}/.exec(
    lock,
  );
  if (!found) throw new Error("api/uv.lock names no git commit of idtrack");
  return found[1];
}

/** RST inline markup as the page writes text: ``code`` and `code` as `code`, roles by their target's last name. */
function plain(text) {
  return text
    .replace(/:py:\w+:`~?([^`]+)`/g, (_, name) => `\`${name.split(".").pop()}\``)
    .replace(/:ref:`([^`<]+?)\s*(<[^>]+>)?`/g, (_, label) => label.trim())
    .replace(/``([^`]+)``/g, "`$1`")
    .replace(/\s+/g, " ")
    .trim();
}

/** A section's title: a line of text underlined by a line of `mark` at least as long. */
function titleAt(lines, i, mark) {
  const under = lines[i + 1] ?? "";
  return /^\S/.test(lines[i]) && under.length >= lines[i].trim().length && new RegExp(`^\\${mark}{3,}$`).test(under);
}

/** The lead sentences of the section "Limitations": one per subsection, its opening text in bold. */
export function limitationsOf(rst) {
  const lines = rst.split("\n");
  const start = lines.findIndex((line, i) => line.trim() === "Limitations" && titleAt(lines, i, "-"));
  if (start < 0) throw new Error("docs/limitations.rst has no section 'Limitations'");
  const rest = lines.slice(start + 2);
  // The section ends where the next section of its level begins.
  const next = rest.findIndex((_, i) => titleAt(rest, i, "-"));
  const section = next < 0 ? rest : rest.slice(0, next);
  const heads = section.flatMap((_, i) => (titleAt(section, i, "~") ? [i] : []));
  if (!heads.length) throw new Error("the section 'Limitations' has no subsections");
  return heads.map((head, k) => {
    const body = section
      .slice(head + 2, heads[k + 1] ?? section.length)
      .filter((line) => !/^\.\. _[^:]+:$/.test(line)) // the label of the next subsection
      .join("\n")
      .trim();
    const lead = /^\*\*([\s\S]+?)\*\*/.exec(body);
    if (!lead) throw new Error(`the limitation '${section[head]}' does not open with a lead sentence in bold`);
    // A lead that is the start of its sentence is marked as continued in idtrack's text.
    const text = plain(lead[1]);
    return /[.?!]$/.test(text) ? text : `${text} …`;
  });
}

const argument = (name) => {
  const at = process.argv.indexOf(name);
  return at < 0 ? null : process.argv[at + 1];
};

async function main() {
  const commit = pinnedCommit(await readFile(lockUrl, "utf8"));
  const from = argument("--from");
  const raw = `https://raw.githubusercontent.com/theislab/idtrack/${commit}/docs/limitations.rst`;
  let rst;
  if (from) {
    rst = await readFile(from, "utf8");
  } else {
    const response = await fetch(raw);
    if (!response.ok) throw new Error(`${raw}: ${response.status}`);
    rst = await response.text();
  }
  const items = limitationsOf(rst);
  const document = {
    about: "Generated by scripts/limitations.mjs from idtrack's docs/limitations.rst at the commit: do not edit.",
    commit,
    source: `${REPOSITORY}/blob/${commit}/docs/limitations.rst#limitations`,
    items,
  };
  const text = await format(JSON.stringify(document), { ...(await resolveConfig(target)), filepath: target });
  if (process.argv.includes("--check")) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== text) {
      console.error(
        "src/generated/limitations.json is not what idtrack's Limitations give: run `npm run limitations`.",
      );
      process.exit(1);
    }
    console.log(`src/generated/limitations.json matches idtrack ${commit.slice(0, 12)} (${items.length} items)`);
  } else {
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, text);
    console.log(`wrote src/generated/limitations.json from idtrack ${commit.slice(0, 12)} (${items.length} items)`);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
